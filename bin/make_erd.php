<?php

/** Write docs/ERD.md (a Mermaid diagram) from the current database schema. */

require_once __DIR__ . '/../vendor/autoload.php';

use App\Core\Database;
use App\Core\Env;

Env::load(dirname(__DIR__));
$pdo = Database::getConnection();

$columns = $pdo->query("
    SELECT TABLE_NAME AS t, COLUMN_NAME AS c, DATA_TYPE AS type, COLUMN_KEY AS k
    FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
    ORDER BY TABLE_NAME, ORDINAL_POSITION")->fetchAll();

$relations = [];
foreach ($pdo->query("
    SELECT TABLE_NAME AS child, COLUMN_NAME AS c, REFERENCED_TABLE_NAME AS parent
    FROM information_schema.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA = DATABASE() AND REFERENCED_TABLE_NAME IS NOT NULL")->fetchAll() as $r) {
    $relations["{$r['child']}.{$r['c']}"] = $r['parent'];
}
// Links of the V1 tables that have no foreign key constraint
$implied = [
    'product.category_id' => 'category', 'discount.product_id' => 'product', 'review.product_id' => 'product',
    'review.user_id' => 'user', 'user_category.user_id' => 'user', 'user_category.category_id' => 'category',
    'orders.user_id' => 'user', 'order_item.order_id' => 'orders', 'order_item.product_id' => 'product',
    'cart.user_id' => 'user', 'cart.product_id' => 'product',
];
$tables = [];
foreach ($columns as $col) {
    $tables[$col['t']][] = $col;
}
foreach ($implied as $key => $parent) {
    [$table, $column] = explode('.', $key);
    if (isset($tables[$table]) && in_array($column, array_column($tables[$table], 'c'), true)) {
        $relations[$key] ??= $parent;
    }
}
ksort($relations);

$out = "# Entity relationship diagram\n\nGenerated by `php bin/make_erd.php`.\n\n```mermaid\nerDiagram\n";
foreach ($relations as $key => $parent) {
    [$child, $column] = explode('.', $key);
    $out .= "    {$parent} ||--o{ {$child} : \"{$column}\"\n";
}
foreach ($tables as $name => $cols) {
    $out .= "    {$name} {\n";
    foreach ($cols as $col) {
        $mark = $col['k'] === 'PRI' ? ' PK' : (isset($relations["{$name}.{$col['c']}"]) ? ' FK' : '');
        $out .= "        {$col['type']} {$col['c']}{$mark}\n";
    }
    $out .= "    }\n";
}
$out .= "```\n";

file_put_contents(dirname(__DIR__) . '/docs/ERD.md', $out);
echo 'Wrote docs/ERD.md (' . count($tables) . " tables)\n";
