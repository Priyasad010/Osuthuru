"""Offline leave-one-out evaluation of the recommender against a popularity baseline.

    docker compose exec web php bin/build_eval_db.php
    docker compose exec ml python -m app.evaluate --database osuthuru_eval
"""
import argparse
from dataclasses import replace
from datetime import date
from pathlib import Path

from . import data as shop
from .recommender import Recommender

K = 5
REPORT = Path(__file__).resolve().parent.parent / "reports" / "recommender_eval.md"


def split(dataset: shop.Dataset):
    """For each customer, hide one product of their latest order (largest product id,
    so that the split is repeatable) if they have other purchases to learn from."""
    sales = dataset.sales
    held_out = {}
    drop = []
    for user_id, rows in sales.groupby("user_id"):
        latest = rows.sort_values(["order_date", "order_id"]).iloc[-1]["order_id"]
        basket = rows[rows["order_id"] == latest]
        target = int(basket["product_id"].max())
        target_rows = rows[rows["product_id"] == target]
        if len(rows) - len(target_rows) < 1:
            continue
        held_out[int(user_id)] = target
        # Remove every purchase of the target by this customer, so it is truly unseen
        drop.extend(target_rows.index)
    return replace(dataset, sales=sales.drop(index=drop)), held_out


def popularity_top(train: shop.Dataset, exclude: set, k: int = K) -> list[int]:
    units = train.sales.groupby("product_id")["quantity"].sum()
    in_stock = train.products[train.products["stock"] > 0]["product_id"]
    ranked = sorted((int(p) for p in in_stock if int(p) not in exclude), key=lambda p: (-float(units.get(p, 0)), p))
    return ranked[:k]


def evaluate(dataset: shop.Dataset, profiles: dict, k: int = K) -> dict:
    """profiles: user_id -> UserProfile holding categories and dosha."""
    train, held_out = split(dataset)
    model = Recommender(train)
    history = train.sales.groupby("user_id")["product_id"].apply(list).to_dict()

    hits = {"popularity": 0, "hybrid": 0}
    for user_id, target in held_out.items():
        bought = [int(p) for p in history.get(user_id, [])]
        profile = replace(profiles.get(user_id, shop.UserProfile()), purchased=bought)
        hits["popularity"] += target in popularity_top(train, set(bought), k)
        hits["hybrid"] += target in model.for_user(profile, k)

    users = len(held_out)
    scores = {
        name: {"precision": h / (users * k) if users else 0.0, "recall": h / users if users else 0.0, "hits": h}
        for name, h in hits.items()
    }
    return {"users": users, "k": k, "scores": scores}


def report(result: dict, database: str, dataset: shop.Dataset) -> str:
    k = result["k"]
    synthetic = database.endswith("_eval")
    lines = ["# Recommender evaluation", ""]
    if synthetic:
        lines += [
            "> **Synthetic data.** The customers and orders in this evaluation were generated by",
            "> `bin/build_eval_db.php`, which gives each customer favourite categories and a dosha and",
            "> makes them buy accordingly. The numbers show that the code can recover those built-in",
            "> patterns. They are **not** evidence of how well it works for real customers.",
            "",
        ]
    lines += [
        f"- Date: {date.today().isoformat()}",
        f"- Database: `{database}`",
        f"- Products: {len(dataset.products)}, orders: {dataset.sales['order_id'].nunique()}, "
        f"customers tested: {result['users']}",
        f"- Method: leave-one-out. One product from each customer's latest order is hidden; each model",
        f"  suggests {k} products the customer has not bought.",
        "",
        f"| Model | precision@{k} | recall@{k} | hits |",
        "|---|---|---|---|",
    ]
    for name, label in (("popularity", "Popularity baseline"), ("hybrid", "Hybrid")):
        s = result["scores"][name]
        lines.append(f"| {label} | {s['precision']:.3f} | {s['recall']:.3f} | {s['hits']} |")
    lines += [
        "",
        f"With one hidden product per customer, the best possible precision@{k} is {1 / k:.3f}.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", default="osuthuru_eval")
    parser.add_argument("--output", default=str(REPORT))
    args = parser.parse_args()

    engine = shop.make_engine(args.database)
    dataset = shop.load_dataset(engine)
    profiles = {int(u): shop.load_profile(engine, int(u)) for u in dataset.sales["user_id"].unique()}
    result = evaluate(dataset, profiles)
    if result["users"] == 0:
        raise SystemExit("Not enough order history to evaluate.")

    path = Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(report(result, args.database, dataset), encoding="utf-8")
    print(path.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
